enum PlaceStatus {
  locked,
  active,
  done,
}

class Place {
  final String id;
  final String name;
  final String imageUrl;
  final List<String> galleryImages;
  final String description;
  final String longDescription;
  final String hint;
  final String location;
  final String historicalBackground;
  final PlaceStatus status;

  const Place({
    required this.id,
    required this.name,
    required this.imageUrl,
    this.galleryImages = const [], // เพิ่มรูปภาพแกลเลอรี
    required this.description,
    required this.longDescription,
    required this.hint,
    required this.location,
    required this.historicalBackground,
    this.status = PlaceStatus.locked, // ค่าเริ่มต้นให้เป็น locked
  });

  Place copyWith({PlaceStatus? status}) {
    return Place(
      id: id,
      name: name,
      imageUrl: imageUrl,
      galleryImages: galleryImages,
      description: description,
      longDescription: longDescription,
      hint: hint,
      location: location,
      historicalBackground: historicalBackground,
      status: status ?? this.status,
    );
  }
}

